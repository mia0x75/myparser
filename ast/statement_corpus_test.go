// SetFlag/GetFlag. The restore path is exercised separately.
type exerciseVisitor struct{}

func (v *exerciseVisitor) Enter(in Node) (Node, bool) {
	_ = in.Text()
	if e, ok := in.(ExprNode); ok {
		e.Format(io.Discard)
		e.SetType(e.GetType())
		e.SetFlag(e.GetFlag())
	}
	return in, false
}

func (v *exerciseVisitor) Leave(in Node) (Node, bool) {
	return in, true
}

func TestStatementCorpusRestoreVisit(t *testing.T) {
	p := myparser.New()
	p.EnableWindowFunc(true)
	for _, sql := range statementCorpus {
		stmts, _, err := p.Parse(sql, "", "")
		if err != nil {
			t.Fatalf("parse %q: %v", sql, err)
		}
		if len(stmts) == 0 {
			t.Fatalf("parse %q: no statements", sql)
		}
		for _, stmt := range stmts {
			var sb strings.Builder
			if err := stmt.Restore(NewRestoreCtx(DefaultRestoreFlags, &sb)); err != nil {
				t.Fatalf("restore %q: %v", sql, err)
			}
			if s, ok := stmt.(SensitiveStmtNode); ok {
				_ = s.SecureText()
			}
			stmt.Accept(&exerciseVisitor{})
			// A skipping visitor covers the early-return branch of Accept.
			stmt.Accept(visitor1{})
			SetFlag(stmt)
			stmt.SetText(stmt.Text())

			if restored := sb.String(); restored != "" {
				if _, _, err := p.Parse(restored, "", ""); err != nil {
					t.Fatalf("reparse %q -> %q: %v", sql, restored, err)
				}
			}
		}
	}
}
